# Verify that every pinned Rust toolchain declaration matches the single source
# in scripts/toolchain.env. Vendored crates under rust-client/vendor/ are not
# inspected: their manifests are inert (patched away in Cargo.toml).
#
# Usage: check_toolchain.sh [--root DIR]

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"

usage() {
    printf 'Usage: %s [--root DIR]\n' "$(basename "$0")" >&2
    printf '  --root DIR   repository root to check (default: %s)\n' "$ROOT" >&2
}

while (($#)); do
    case "$1" in
        --root)
            (($# >= 2)) || {
                printf 'Error: --root requires a value.\n' >&2
                exit 2
            }
            ROOT="$2"
            shift
            ;;
        --root=*) ROOT="${1#--root=}" ;;
        -h | --help)
            usage
            exit 0
            ;;
        *)
            printf 'Error: unknown argument: %s\n' "$1" >&2
            usage
            exit 2
            ;;
    esac
    shift
done

if ! ROOT="$(cd -- "$ROOT" 2>/dev/null && pwd)"; then
    printf 'FAIL: root directory does not exist: %s\n' "$ROOT" >&2
    exit 1
fi

FAILED=0

fail() {
    printf 'FAIL: %s\n' "$*" >&2
    FAILED=1
}

TOOLCHAIN_ENV="$ROOT/scripts/toolchain.env"
if [[ ! -f "$TOOLCHAIN_ENV" ]]; then
    printf 'FAIL: %s: toolchain pin file is missing\n' "scripts/toolchain.env" >&2
    exit 1
fi

# shellcheck source=/dev/null
source "$TOOLCHAIN_ENV"

if [[ -z "${RUST_TOOLCHAIN:-}" ]]; then
    printf 'FAIL: %s: RUST_TOOLCHAIN is not set\n' "scripts/toolchain.env" >&2
    exit 1
fi

# First `key = "value"` assignment in the file. The pin files are tiny and
# generated by humans, so a full TOML parser would be overkill here.
read_pin() {
    local file="$1" key="$2"
    sed -n "s/^[[:space:]]*${key}[[:space:]]*=[[:space:]]*\"\([^\"]*\)\".*/\1/p" "$file" |
        sed -n '1p'
}

check_pin() {
    local file="$1" key="$2" expected="$3" rel actual
    rel="${file#"$ROOT/"}"
    if [[ ! -f "$file" ]]; then
        fail "$rel: file is missing"
        return
    fi
    actual="$(read_pin "$file" "$key")"
    if [[ -z "$actual" ]]; then
        fail "$rel: no \"$key\" entry"
        return
    fi
    if [[ "$actual" != "$expected" ]]; then
        fail "$rel: $key \"$actual\" does not match RUST_TOOLCHAIN \"$expected\" from scripts/toolchain.env"
    fi
}

check_pin "$ROOT/rust-client/rust-toolchain.toml" channel "$RUST_TOOLCHAIN"
check_pin "$ROOT/rust-server/rust-toolchain.toml" channel "$RUST_TOOLCHAIN"
check_pin "$ROOT/rust-client/Cargo.toml" rust-version "$RUST_TOOLCHAIN"
check_pin "$ROOT/rust-server/Cargo.toml" rust-version "$RUST_TOOLCHAIN"

if ((FAILED != 0)); then
    exit 1
fi

printf 'Toolchain pins consistent: RUST_TOOLCHAIN=%s\n' "$RUST_TOOLCHAIN"
